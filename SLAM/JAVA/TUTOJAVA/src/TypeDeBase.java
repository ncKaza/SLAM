public class TypeDeBase {
    public static void main(String[] args) {
        //types numériques entiers
        int in = 10000;
        byte bt = 14;
        short sh = 123;
        long lg = 123456789;

        //Afficher les variables
        System.out.println("La variable in est : "+in);
        System.out.println("La variable byte est : "+bt);
        System.out.println("La variable short est : "+sh);
        System.out.println("La variable long est : "+lg);

        //types décimaux
        float fl = 2.5f;
         //--> Pour préciser que c'est un float on ajoute 'f'

        double db = 2.6;
        //par défaut les nombres à virgules sont de type double

        //afficher les variables
        System.out.println("La variable float est : "+fl);
        System.out.println("La variable double est : "+db);
    }


}
